const MAP = new Map<string, DeptId>();
for (const [dept, names] of Object.entries(DICTIONARY) as [DeptId, string[]][]) {
  for (const n of names) {
    const k = normalizeName(n);
    if (!MAP.has(k)) MAP.set(k, dept);
  }
}

export function departmentFor(key: string, learned: DeptId | null): DeptId {
  if (learned) return learned;
  const exact = MAP.get(key);
  if (exact) return exact;
  const first = key.split(' ')[0];
  return (first && MAP.get(first)) || 'other';
}
